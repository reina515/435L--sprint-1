"""
Creates the .env file with freshly generated random secrets.

    python setup_env.py              # create .env (refuses to overwrite)
    python setup_env.py --force      # regenerate (WARNING: existing encrypted data becomes unreadable)

Lab 2: "Generate a key and store it safely, outside the codebase".
The .env file is listed in .gitignore so the secrets never reach GitHub.
"""
import os
import secrets
import sys

from cryptography.fernet import Fernet

ROOT = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(ROOT, ".env")

TEMPLATE = """# ===== Generated by setup_env.py - DO NOT COMMIT THIS FILE =====
# Your full name: shown in the X-Student-Name header of every API response
STUDENT_NAME={student}

# --- Secrets ---
JWT_SECRET={jwt}
FERNET_KEY={fernet}
HMAC_KEY={hmac}
SERVICE_API_KEY={service}

# --- Token lifetime ---
JWT_EXPIRES_MINUTES=60

# --- Database (relative to the project root) ---
DATABASE_PATH=database/security.db

# --- Services ---
HOST=127.0.0.1
USER_SERVICE_PORT=5001
AUDIT_SERVICE_PORT=5005
NOTIFICATION_SERVICE_PORT=5008

# --- Security options ---
MAX_FAILED_LOGINS=5
FLASK_DEBUG=false
# Set to true after running `python generate_cert.py` to serve the APIs over HTTPS
USE_HTTPS=false
"""


def main():
    if os.path.exists(ENV_PATH) and "--force" not in sys.argv:
        print(".env already exists - nothing changed (use --force to regenerate the secrets).")
        return
    student = input("Your full name (for the X-Student-Name header): ").strip() or "<Your Full Name>"
    content = TEMPLATE.format(
        student=student,
        jwt=secrets.token_urlsafe(48),
        fernet=Fernet.generate_key().decode(),
        hmac=secrets.token_urlsafe(48),
        service=secrets.token_urlsafe(32),
    )
    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    try:
        os.chmod(ENV_PATH, 0o600)
    except OSError:
        pass
    print(f"Created {ENV_PATH}")
    print("Your SERVICE_API_KEY is inside .env (you need it only for testing internal calls).")


if __name__ == "__main__":
    main()
